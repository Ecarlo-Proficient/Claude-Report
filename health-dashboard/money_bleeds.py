def check_rp_wrapup(wip_path: Path) -> Tuple[List[Dict[str, Any]], str]:
    """'Test - RP' SLAB rows 100% complete in the General List but not fully
    billed — waiting on punch, chase to get paid. FTW lines are skipped: the
    General List's 100% column is slab-only; the FTW completion section
    isn't used (the user 2026-07-16). Returns (rows, synced)."""
    wb = load_workbook(wip_path, data_only=True, read_only=True)
    ws = wb[RP_TEST_SHEET]
    # FIND the header row — never assume row 1 (2026-08-03). The tab grew a
    # title block, so the header sits below it and a hard-coded row 1 read
    # silently returned nothing at all.
    hdr_row = next((r for r in range(1, 16)
                    if any(str(ws.cell(r, c).value or "").strip().upper()
                           == "PROJECT #"
                           for c in range(1, (ws.max_column or 0) + 1))), None)
    if hdr_row is None:
        wb.close()
        return [], ""
    hdr = {str(ws.cell(hdr_row, c).value or "").strip().upper(): c
           for c in range(1, ws.max_column + 1)}

    def col(r, label):
        c = hdr.get(label)
        return ws.cell(r, c).value if c else None

    # LAST SYNCED left the lean 'Test - RP' layout (2026-08-07); fall back to
    # the report date on the title row (B2: "REPORT DATE: …").
    synced = ""
    for rr in range(1, hdr_row):
        v = str(ws.cell(rr, 2).value or "")
        if "REPORT DATE" in v.upper():
            synced = v.split(":", 1)[-1].strip()
            break
    rows = []
    for r in range(hdr_row + 1, ws.max_row + 1):
        proj = col(r, "PROJECT #")
        if not proj:
            continue
        synced = str(col(r, "LAST SYNCED") or synced)
        proj = str(proj).strip().upper()
        if proj.endswith("-FTW"):
            continue                      # 100% is slab-only — FTW ignored
        notes = str(col(r, "NOTES") or "")
        status = str(col(r, "STATUS") or "").strip()
        if "100% complete (list)" not in notes or status.lower() != "active":
            continue
        # TOTAL CONTRACT PRICE is a live formula on this tab (so the owner's
        # edits add up in Excel), and an openpyxl-written formula has no cached
        # value — fall back to its components, which are always plain numbers.
        contract = float(col(r, "TOTAL CONTRACT PRICE")
                         or (float(col(r, "ORIGINAL CONTRACT") or 0)
                             + float(col(r, "APPROVED COs") or 0)))
        billed = float(col(r, "BILLED TO DATE") or 0)
        left = float(col(r, "LEFT TO BILL") or (contract - billed))
        if left <= 0:
            continue
        # WHY: the classification segment, minus the RED echo + the 100% tag
        why = "; ".join(
            s.strip() for s in notes.split(";")
            if s.strip() and not s.strip().startswith("RED:")
            and s.strip() != "100% complete (list)") or notes
        rows.append({"project": proj, "name": str(col(r, "PROJECT NAME") or ""),
                     "client": str(col(r, "CLIENT") or ""),
                     "contract": contract, "billed": billed, "left": left,
                     "note": why})
    wb.close()
    rows.sort(key=lambda x: -x["left"])
    return rows, synced


