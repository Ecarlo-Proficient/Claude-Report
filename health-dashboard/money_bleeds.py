def main() -> int:
    ap = argparse.ArgumentParser(description="Money Bleeds — company health exceptions report")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUTPUT)
    args = ap.parse_args()

    print("\n  MONEY BLEEDS — draws↔invoices · lien clock · RP wrap-up")
    print("  " + "─" * 60)

    # Hard-fail preflight — mounts must be present, same pattern as Synology.
    problems = []
    if not WIP_EXCEL_PATH.exists():
        problems.append(f"WIP workbook not found: {WIP_EXCEL_PATH} (OneDrive synced?)")
    if not BILL_TRACKER_PATH.exists():
        problems.append(f"Bill Tracker not found: {BILL_TRACKER_PATH} (run sync-ap)")
    if not MFD_ROOT.is_dir():
        problems.append(f"Multi Family volume not mounted: {MFD_ROOT}")
    if not CP_ACTIVE_DIR.is_dir():
        problems.append(f"Common volume not mounted: {CP_ACTIVE_DIR}")
    if problems:
        for p in problems:
            print(f"  ✗ {p}")
        return 2

    # one QBO session + one pull per entity for the whole run (the user
    # 2026-07-24) — invoices/POs are downloaded once and shared by every check
    qc = QboCache(verbose=True)
    print("  QBO project-customer map …")
    proj_map = qc.project_customer_map()

    print("  1a. MFD draws vs invoices …")
    mfd = check_mfd_draws(qc, proj_map)
    print(f"      {len(mfd)} active MFD project(s), "
          f"{sum(1 for r in mfd if r['verdict'] == 'RED')} RED")

    print("  1b. CP draws vs invoices …")
    cp = check_cp_draws(qc, proj_map)
    print(f"      {len(cp)} CP project(s) with draws, "
          f"{sum(1 for r in cp if r['verdict'] == 'RED')} RED")

    print("  2.  Lien clock (work month = invoice month) …")
    lien, reten, leases = check_lien_clock(qc, proj_map)
    past = sum(1 for r in lien if r["status"] == "PAST")
    urgent = sum(1 for r in lien if r["status"] == "URGENT")
    print(f"      {len(lien)} open invoice(s) on the clock — "
          f"{past} PAST, {urgent} URGENT · {len(reten)} retainage (own track) "
          f"· {len(leases)} lease/note excluded")

    print("  3.  RP billing status (poured vs backlog) …")

    def _billed_for(key):
        cust = proj_map.get(key)
        if not cust:
            return None
        return sum(float(i.get("TotalAmt") or 0)
                   for i in qc.invoices_for_customer(cust["id"]))

    rp = rp_billing.build(_billed_for)
    print(f"      INVOICE NOW {len(rp['invoice_now'])} scope(s) = ${rp['due_total']:,.0f}"
          f"  ·  backlog {len(rp['backlog'])} = ${rp['backlog_total']:,.0f}"
          f"  ·  draw-based {len(rp.get('draw_based', []))} = ${rp.get('draw_total', 0):,.0f}")

    print("  4.  Unused POs ≥30 days old …")
    pos = check_unused_pos(qc)
    print(f"      {len(pos)} open PO(s), ${sum(r['amount'] for r in pos):,.0f} committed with no bill")

    print("  5.  Open bills (AP) from the Bill Tracker …")
    bills, bills_synced = read_open_bills(BILL_TRACKER_PATH)
    paid_out = sum(b["open"] for b in bills if b["ar"] == "paid")
    print(f"      {len(bills)} open bill(s), ${sum(b['open'] for b in bills):,.0f} to go out "
          f"(${paid_out:,.0f} already funded by clients) · tracker synced {bills_synced}")

    write_workbook(args.out, mfd, cp, lien, reten, leases, rp, pos,
                   bills, bills_synced)
    print(f"\n  ✓ {args.out}  (chmod 600)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
