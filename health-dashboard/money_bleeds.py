def _sheet(wb: Workbook, title: str, headers: List[str], widths: List[int]):
    ws = wb.create_sheet(title)
    ws.append(headers)
    for c in range(1, len(headers) + 1):
        cell = ws.cell(1, c)
        cell.font = _WHITE
        cell.fill = _HDR_FILL
        cell.border = _BORDER
        cell.alignment = Alignment(vertical="center", wrap_text=True,
                                   horizontal="center")
    for i, w in enumerate(widths):
        ws.column_dimensions[get_column_letter(i + 1)].width = w
    ws.row_dimensions[1].height = 28
    ws.freeze_panes = "A2"
    return ws


def _band_row(ws, ncols: int, label: str, color: str) -> None:
    """A full-width colored section header inside a sheet."""
    ws.append([label] + [""] * (ncols - 1))
    r = ws.max_row
    ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=ncols)
    c = ws.cell(r, 1)
    c.fill = PatternFill("solid", fgColor=color)
    c.font = Font(bold=True, color="FFFFFF", size=11)
    c.alignment = Alignment(vertical="center", indent=1)
    ws.row_dimensions[r].height = 20


def _zebra(ws, ncols: int, idx: int, money_cols=(), status_col=0,
           status="") -> None:
    """Border + banding on the just-appended data row; money cols formatted;
    optional status-cell fill."""
    r = ws.max_row
    shade = _ZEBRA if idx % 2 else None
    for c in range(1, ncols + 1):
        cell = ws.cell(r, c)
        cell.border = _BORDER
        if shade:
            cell.fill = shade
    for c in money_cols:
        ws.cell(r, c).number_format = CUR
    if status_col and status in _STATUS_FILL:
        sc = ws.cell(r, status_col)
        sc.fill = PatternFill("solid", fgColor=_STATUS_FILL[status])
        sc.font = _BOLD


def _subtotal(ws, ncols: int, label_col: int, label: str,
              amount_col: int, amount: float) -> None:
    ws.append([""] * ncols)
    r = ws.max_row
    for c in range(1, ncols + 1):
        ws.cell(r, c).fill = _SUB_FILL
        ws.cell(r, c).border = _BORDER
    ws.cell(r, label_col, label).font = _BOLD
    a = ws.cell(r, amount_col, amount)
    a.number_format = CUR
    a.font = _BOLD


def _data_bar(ws, col: int, r1: int, r2: int, color="8EAADB") -> None:
    if r2 >= r1:
        L = get_column_letter(col)
        ws.conditional_formatting.add(
            f"{L}{r1}:{L}{r2}",
            DataBarRule(start_type="num", start_value=0, end_type="max",
                        color=color, showValue=True))


def _color_scale(ws, col: int, r1: int, r2: int, low_is_bad=True) -> None:
    if r2 < r1:
        return
    L = get_column_letter(col)
    red, grn = "F8696B", "63BE7B"
    lo, hi = (red, grn) if low_is_bad else (grn, red)
    ws.conditional_formatting.add(
        f"{L}{r1}:{L}{r2}",
        ColorScaleRule(start_type="min", start_color=lo,
                       mid_type="percentile", mid_value=50, mid_color="FFEB84",
                       end_type="max", end_color=hi))


def _verdict_cf(ws, col: int, r1: int, r2: int) -> None:
    """Highlight-rule the verdict/status text so filtering/sorting keeps color."""
    if r2 < r1:
        return
    L = get_column_letter(col)
    rng = f"{L}{r1}:{L}{r2}"
    for words, fill in (
        (("RED", "PAST", "URGENT"), "FFC7CE"),
        (("REVIEW", "PENDING", "WATCH"), "FFEB9C"),
        (("PASS", "OK"), "C6EFCE"),
    ):
        for w in words:
            ws.conditional_formatting.add(
                rng, CellIsRule(operator="equal", formula=[f'"{w}"'],
                                fill=PatternFill("solid", fgColor=fill)))


def _subband_row(ws, ncols: int, label: str, color: str) -> None:
    """A lighter sub-section header inside a group."""
    ws.append([label] + [""] * (ncols - 1))
    r = ws.max_row
    ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=ncols)
    c = ws.cell(r, 1)
    c.fill = PatternFill("solid", fgColor=color)
    c.font = Font(bold=True, italic=True, color="404040")
    c.alignment = Alignment(vertical="center", indent=2)


def _finish(ws, ncols: int, header_row=1) -> None:
    ws.auto_filter.ref = f"A{header_row}:{get_column_letter(ncols)}{ws.max_row}"


def _write_open_bills(wb, bills: List[dict], synced: str) -> None:
    """One sheet: AP bills that need money to go out, grouped by AR state
    (paid by client / not paid / not invoiced), each split lien-coming-up vs
    not (the user 2026-07-17). Sub who billed us can lien us → pay the
    coming-up ones before the deadline; the paid-by-client not-yet-due bunch
    is 'money out by this month's lien-15'."""
    cols = ["LIEN", "SUB LIEN DEADLINE", "DAYS", "SUB (VENDOR)", "DIV",
            "PROJECT #", "BILL #", "BILL DATE", "OPEN BAL $", "GC INVOICE",
            "CLIENT PAID", "STATUS"]
    ws = _sheet(wb, "Open Bills (AP)", cols,
                [10, 16, 7, 26, 6, 11, 12, 12, 15, 12, 12, 24])

    groups = [
        ("paid",   "PAID BY CLIENT — money is in, pay it out", "BF8F00"),
        ("unpaid", "CLIENT HASN'T PAID US — owe the sub, collect from the GC", "C00000"),
        ("noinv",  "NO INVOICE ISSUED YET — bill the GC first", "7030A0"),
    ]
    for ar, title, color in groups:
        grp = [b for b in bills if b["ar"] == ar]
        if not grp:
            continue
        gtot = sum(b["open"] for b in grp)
        _band_row(ws, 12, f"  {title}   —   {len(grp)} bill(s)   —   "
                          f"${gtot:,.0f} to go out", color)
        g_start = ws.max_row + 1
        # split: lien coming up (due) first, then the rest
        for sub_key, sub_label, sub_color in (
            ("due",  "coming up for lien — pay before the deadline", "FCE4D6"),
            ("rest", "not due for lien — clear by this month's 15th", "EDEDED"),
        ):
            part = [b for b in grp if (b["lien"] == "due") == (sub_key == "due")]
            if not part:
                continue
            part.sort(key=lambda b: (b["days"] if b["days"] is not None else 9999,
                                     -b["open"]))
            _subband_row(ws, 12, f"    {sub_label}  ·  {len(part)} bill(s)  ·  "
                                 f"${sum(b['open'] for b in part):,.0f}", sub_color)
            s1 = ws.max_row + 1
            for i, b in enumerate(part):
                lien_tag = {"due": "DUE", "expired": "expired",
                            "far": "", "n/a": "n/a"}[b["lien"]]
                ws.append([
                    lien_tag,
                    b["deadline"].isoformat() if b["deadline"] else "—",
                    b["days"] if b["days"] is not None else "",
                    b["vendor"], b["division"], b["project"], b["bill"],
                    b["date"].isoformat() if b["date"] else "—",
                    b["open"], b["invoice"],
                    b["paid_date"].isoformat() if b["paid_date"] else "—",
                    b["status"],
                ])
                status = "URGENT" if b["lien"] == "due" else ""
                _zebra(ws, 12, i, money_cols=(9,), status_col=1, status=status)
                ws.row_dimensions[ws.max_row].outlineLevel = 1
            _data_bar(ws, 9, s1, ws.max_row)
            _subtotal(ws, 12, 8, "subtotal", 9, sum(b["open"] for b in part))
        # group total
        _subtotal(ws, 12, 8, f"{title.split(' —')[0]} TOTAL", 9, gtot)
        ws.cell(ws.max_row, 8).font = Font(bold=True, size=11)
    _finish(ws, 12)
    ws.sheet_properties.tabColor = "C55A11"
    note = ("Source: Bill Tracker.xlsx (bill-tracker / sync-ap) — read-only, "
            f"last synced {synced or 'unknown'}. Lien = the SUB's deadline to "
            "lien us (work month ≈ bill date; RP 15th of 2nd month, CP/MFD 3rd).")
    ws.append([]); ws.append([note])
    ws.cell(ws.max_row, 1).font = Font(italic=True, color="808080")


