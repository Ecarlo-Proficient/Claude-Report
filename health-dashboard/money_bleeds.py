def read_active_mfd(wip_path: Path) -> List[Tuple[str, str]]:
    """MFD#### rows from the 'WIP Master' tab — the master sheet IS the MFD
    source for active jobs (same rule as wip/master_wip_test.py)."""
    wb = load_workbook(wip_path, data_only=True, read_only=True)
    ws = wb[MASTER_SHEET]
    out = []
    for r in range(4, ws.max_row + 1):
        proj = ws.cell(r, 1).value
        if proj and str(proj).strip().upper().startswith("MFD"):
            out.append((str(proj).strip().upper(),
                        str(ws.cell(r, 2).value or "").strip()))
    wb.close()
    return out


def find_mfd_project_folder(proj: str) -> Optional[Path]:
    """<MFD root>/<CLIENT>/<MFD### - NAME>. Scans client dirs (skipping
    recycle/completed/non-active); word-boundary match so MFD177 never
    matches MFD1770."""
    want = re.compile(rf"^{re.escape(proj)}\b", re.IGNORECASE)
    try:
        clients = [d for d in MFD_ROOT.iterdir() if d.is_dir()
                   and d.name.strip().lower() not in _SKIP_DIRS]
    except OSError:
        return None
    for client in clients:
        try:
            for sub in client.iterdir():
                if sub.is_dir() and want.match(sub.name.strip()):
                    return sub
        except OSError:
            continue
    return None


def find_mfd_draws_folder(project_folder: Path) -> Optional[Path]:
    """'PM MISC/DRAWS' first (the standard layout), else any 'Draw(s)' dir
    within two levels."""
    direct = project_folder / "PM MISC" / "DRAWS"
    if direct.is_dir():
        return direct
    for depth1 in project_folder.iterdir():
        if not depth1.is_dir():
            continue
        if draws.DRAWS_FOLDER_RE.match(depth1.name.strip()):
            return depth1
        try:
            for depth2 in depth1.iterdir():
                if depth2.is_dir() and draws.DRAWS_FOLDER_RE.match(depth2.name.strip()):
                    return depth2
        except OSError:
            continue
    return None


# An MFD draw folder holds the pay application AND the lien releases that ride
# along with it. The releases are named for what they are ('Conditional Release
# … August Draw 2026'), so the release test runs FIRST — otherwise a release
# carrying the word 'Draw' would masquerade as the draw itself.
_MFD_RELEASE_RE = re.compile(r"release|waiver|lien", re.IGNORECASE)
_MFD_DRAWDOC_RE = re.compile(r"draw|pay\s*app", re.IGNORECASE)


def mfd_draw_documents(draw_folder: Path) -> List[str]:
    """The pay-application PDFs inside a draw folder (recursing, because a job
    billing several contracts files one draw per contract subfolder).

    MFD draws are PDFs — there is no G702 to read an amount off, so the
    presence of the draw document IS the signal that the draw was actually
    built and sent. A folder holding only conditional/unconditional releases
    is a placeholder opened ahead of the billing, not money we can invoice."""
    docs: List[str] = []
    try:
        entries = list(draw_folder.rglob("*"))
    except OSError:
        return docs
    for f in entries:
        try:
            if not f.is_file() or f.suffix.lower() != ".pdf":
                continue
        except OSError:
            continue
        if _MFD_RELEASE_RE.search(f.name):
            continue
        if _MFD_DRAWDOC_RE.search(f.name):
            docs.append(f.name)
    return sorted(docs)


def scan_mfd_draws(draws_dir: Path):
    """(built, staged) for a project's DRAWS folder.

    built  = highest-numbered draw folder that holds a pay application —
             the latest real draw, and the only one we test for an invoice.
    staged = a higher-numbered folder that exists but holds no draw document
             yet (placeholder opened ahead of the work). Reported, never
             judged: there is nothing to invoice until the draw is built.

    Deliberately only the latest draw of each kind — older draws are left
    alone because the pre-2026 folders don't follow this naming."""
    folders = []
    try:
        entries = list(draws_dir.iterdir())
    except OSError:
        return None, None
    for entry in entries:
        if not entry.is_dir():
            continue
        parsed = _parse_mfd_draw_name(entry.name)
        if not parsed:
            continue
        num, month, year = parsed
        folders.append((num, dt.date(year, month, 1), entry.name.strip(),
                        mfd_draw_documents(entry)))
    if not folders:
        return None, None
    folders.sort(key=lambda f: f[0])
    built = next((f for f in reversed(folders) if f[3]), None)
    top = folders[-1]
    staged = top if (not top[3] and (built is None or top[0] > built[0])) else None
    return built, staged


def check_mfd_draws(qc: QboCache,
                    proj_map: Dict[str, dict]) -> List[Dict[str, Any]]:
    """One row per active MFD project: the latest BUILT draw (the folder
    holding an actual pay application) vs latest QBO invoice date. PASS =
    latest invoice lands in/after that draw's month. A higher-numbered
    placeholder folder is reported in STAGED NEXT, never judged."""
    results = []
    today = _today()
    for proj, name in read_active_mfd(WIP_EXCEL_PATH):
        row = {"project": proj, "name": name, "draw": "", "draw_month": None,
               "staged": "", "last_invoice": None, "verdict": "", "detail": ""}
        results.append(row)

        folder = find_mfd_project_folder(proj)
        if folder is None:
            row["verdict"] = "REVIEW"
            row["detail"] = "No project folder found on the Multi Family volume"
            continue
        draws_dir = find_mfd_draws_folder(folder)
        if draws_dir is None:
            row["verdict"] = "REVIEW"
            row["detail"] = f"No DRAWS folder under {folder.name}"
            continue
        built, staged = scan_mfd_draws(draws_dir)
        if staged is not None:
            row["staged"] = f"{staged[2]} — folder only, no draw doc yet"
        if built is None:
            row["verdict"] = "REVIEW"
            row["detail"] = ("No built draw in the DRAWS folder — "
                             + (f"{staged[2]} is staged but holds no pay application"
                                if staged is not None
                                else "no numbered draw subfolders"))
            continue
        draw_num, draw_month, draw_label, draw_docs = built
        row["draw"] = draw_label
        row["draw_month"] = draw_month

        cust = proj_map.get(proj)
        if cust is None:
            row["verdict"] = "RED"
            row["detail"] = "No QBO project customer matches this project #"
            continue
        invs = qc.invoices_for_customer(cust["id"])
        last = max((_parse_date(i.get("TxnDate")) for i in invs
                    if _parse_date(i.get("TxnDate"))), default=None)
        row["last_invoice"] = last

        docs = f"{len(draw_docs)} pay app(s)" if draw_docs else "pay app"
        if last is not None and last >= draw_month:
            row["verdict"] = "PASS"
            row["detail"] = f"Draw {draw_num} ({docs}) invoiced ({last.isoformat()})"
        elif (draw_month.year, draw_month.month) == (today.year, today.month):
            row["verdict"] = "PENDING"
            row["detail"] = (f"Draw {draw_num} is built ({docs}) and is "
                             f"current-month — invoice not in QBO yet")
        else:
            row["verdict"] = "RED"
            row["detail"] = (f"Draw {draw_num} ({draw_label}) is BUILT ({docs}) "
                             f"but has NO QBO invoice — last invoice "
                             f"{last.isoformat() if last else 'NEVER'}. INVOICE THIS.")
    return results


# ────────────────── check 1b — CP draws vs invoices ────────────────

def check_cp_draws(qc: QboCache,
                   proj_map: Dict[str, dict]) -> List[Dict[str, Any]]:
    """One row per active CP project folder that has a draw: G702
    earned-less-retainage (cumulative, what should be invoiced) vs the sum
    of ALL QBO invoices for the project. Shortfall = a draw never invoiced."""
    results = []
    try:
        folders = sorted(d for d in CP_ACTIVE_DIR.iterdir() if d.is_dir())
    except OSError as e:
        raise SystemExit(f"✗ CP active dir unreadable: {CP_ACTIVE_DIR} ({e})")
    for folder in folders:
        m = _CP_FOLDER_RE.match(folder.name.strip())
        if not m:
            continue
        proj = m.group(1).upper()
        found = draws.find_latest_draw(folder)
        if not found:
            continue                              # no draw yet — nothing to verify
        draw_num, draw_file = found
        row = {"project": proj, "name": folder.name, "draw_num": draw_num,
               "earned": None, "invoiced": None, "verdict": "", "detail": ""}
        results.append(row)

        data, flags = draws.read_draw_g702(draw_file)
        earned = (data or {}).get("earned_less_retainage")
        if earned is None:
            earned = (data or {}).get("billed")    # fallback: gross billed
        if earned is None:
            row["verdict"] = "REVIEW"
            row["detail"] = "; ".join(flags) or f"Draw #{draw_num} G702 unreadable"
            continue
        row["earned"] = earned

        cust = proj_map.get(proj)
        if cust is None:
            row["verdict"] = "RED"
            row["detail"] = "No QBO project customer matches this project #"
            continue
        invs = qc.invoices_for_customer(cust["id"])
        invoiced = sum(float(i.get("TotalAmt") or 0) for i in invs)
        row["invoiced"] = invoiced

        gap = earned - invoiced
        if gap > CP_TOLERANCE:
            row["verdict"] = "RED"
            row["detail"] = (f"Draw #{draw_num} earned ${earned:,.2f} but QBO "
                             f"invoiced ${invoiced:,.2f} — ${gap:,.2f} never invoiced")
        else:
            row["verdict"] = "PASS"
            row["detail"] = f"QBO invoiced covers draw #{draw_num}"
    return results


# ────────────────── check 2 — lien clock on open invoices ───────────

def check_lien_clock(qc: QboCache,
                     proj_map: Dict[str, dict]) -> Tuple[
        List[Dict[str, Any]], List[Dict[str, Any]], List[Dict[str, Any]]]:
    """Every open invoice → notice deadline + days left. Work month =
    invoice month (the user 2026-07-16: RP invoices go out the day the job
    finishes; draws bill their work month). Returns (monthly_rows,
    retainage_rows, lease_rows) — retainage runs its own statutory track;
    equipment-lease/note invoices aren't construction income at all."""
    today = _today()
    monthly, retainage, leases = [], [], []
    for inv in qc.open_invoices():
        txn = _parse_date(inv.get("TxnDate"))
        if txn is None:
            continue
        cust_name = (inv.get("CustomerRef") or {}).get("name") or ""
        div = _division(cust_name)
        proj = qbo_api.extract_proj(cust_name) or ""
        # Invoice CustomerRef.name is the bare display name — the parent
        # chain comes from the customer map's FullyQualifiedName.
        parent = _parent(cust_name)
        if not parent and proj and proj in proj_map:
            fqn = proj_map[proj].get("fully_qualified_name", "")
            parent = ":".join(fqn.split(":")[:-1])
        row = {
            "division": div if div != "?" else "? (review)",
            "project": proj,
            "parent": parent,
            "customer": cust_name,
            "doc": inv.get("DocNumber") or "",
            "txn_date": txn,
            "balance": float(inv.get("Balance") or 0),
        }
        if _is_lease_invoice(inv):
            row["note"] = "Equipment lease / note payment — not construction income"
            leases.append(row)
            continue
        if _is_retainage_invoice(inv):
            row["note"] = ("Retainage — separate track (§ 53.057, keyed to "
                           "completion, not the monthly clock)")
            retainage.append(row)
            continue
        deadline = notice_deadline(txn.year, txn.month, div if div != "?" else "RP")
        days = (deadline - today).days
        row["work_month"] = dt.date(txn.year, txn.month, 1)
        row["deadline"] = deadline
        row["days_left"] = days
        row["status"] = ("PAST" if days < 0 else
                         "URGENT" if days <= URGENT_DAYS else
                         "WATCH" if days <= WATCH_DAYS else "OK")
        monthly.append(row)
    # Don't show OK rows — the sheet is a deadline watchlist, not a ledger
    # (the user 2026-07-17). Only PAST / URGENT / WATCH earn a line.
    monthly = [r for r in monthly if r["status"] != "OK"]
    monthly.sort(key=lambda r: r["days_left"])
    retainage.sort(key=lambda r: r["txn_date"])
    leases.sort(key=lambda r: -r["balance"])
    return monthly, retainage, leases


# ────────────────── check 4 — unused POs ≥30 days old ───────────────

PO_STALE_DAYS = 30


def check_unused_pos(qc: QboCache) -> List[Dict[str, Any]]:
    """Open QBO purchase orders with NO bill linked, aged ≥30 days — money
    committed on paper that never got used (or a bill that never got entered
    against it). Newest first within the flagged set, by value."""
    today = _today()
    rows = []
    for po in qc.purchase_orders():
        if po.get("POStatus") != "Open":   # POStatus isn't queryable — filter here
            continue
        if po.get("LinkedTxn"):            # a bill/other txn already references it
            continue
        txn = _parse_date(po.get("TxnDate"))
        if txn is None:
            continue
        age = (today - txn).days
        if age < PO_STALE_DAYS:
            continue
        # cost code / job from the first line's customer + description
        job = ""
        for line in po.get("Line", []) or []:
            det = line.get("ItemBasedExpenseLineDetail") or \
                line.get("AccountBasedExpenseLineDetail") or {}
            cust = (det.get("CustomerRef") or {}).get("name") or ""
            job = qbo_api.extract_proj(cust) or job
            if job:
                break
        rows.append({
            "doc": str(po.get("DocNumber") or ""),
            "txn_date": txn,
            "age": age,
            "vendor": (po.get("VendorRef") or {}).get("name") or "",
            "project": job,
            "amount": float(po.get("TotalAmt") or 0),
            "memo": (po.get("Memo") or "")[:80],
        })
    rows.sort(key=lambda r: -r["amount"])
    return rows


# ────────────────── check 5 — open bills (AP) from Bill Tracker ─────
# READ-ONLY off the Bill Tracker workbook (bill-tracker/ owns the matching:
# each bill → the GC invoice that authorizes payment + client payment date).
# We only re-bucket it here (the user 2026-07-17):
#   AR spine — paid by client / client not paid / no invoice issued yet
#   crossed with the SUB's lien clock (a sub can lien us if unpaid): a bill is
#   "lien coming up" when the sub's notice deadline is within the current cycle.
# "Money out by this month's lien-15" = the paid-by-client, not-yet-due bucket.

BILL_LIEN_WINDOW = 45           # days-out that counts as "coming up"
BILL_LIEN_GRACE = 15            # just-passed deadlines still count (pay now)


def _ar_state(minv, pdate) -> str:
    if minv and pdate:
        return "paid"           # client already paid us for this work
    if minv:
        return "unpaid"         # invoiced the GC, not collected yet
    return "noinv"              # not even billed to the GC


def _bill_lien(division: str, bill_date, today: dt.date):
    """The sub's lien deadline on this bill (work month ≈ bill date). Returns
    (deadline, days_left, state) — state in due/far/expired/n-a."""
    div = (division or "").upper()
    if div not in ("RP", "CP", "MFD") or not bill_date:
        return None, None, "n/a"
    bd = bill_date.date() if isinstance(bill_date, dt.datetime) else bill_date
    deadline = notice_deadline(bd.year, bd.month, div)
    days = (deadline - today).days
    if days < -BILL_LIEN_GRACE:
        state = "expired"       # sub's lien window closed — lower urgency
    elif days <= BILL_LIEN_WINDOW:
        state = "due"           # coming up (pay before they can lien)
    else:
        state = "far"
    return deadline, days, state


def read_open_bills(path: Path) -> Tuple[List[Dict[str, Any]], str]:
    """Open (unpaid-to-sub) bills from the Bill Tracker 'Bills' sheet,
    aggregated to bill level, tagged with AR state + lien state. Returns
    (rows, tracker_synced)."""
    from datetime import datetime as _dtm
    synced = ""
    try:
        synced = _dtm.fromtimestamp(path.stat().st_mtime).strftime("%Y-%m-%d %H:%M")
    except OSError:
        pass
    wb = load_workbook(path, read_only=True, data_only=True)
    ws = wb["Bills"]
    it = ws.iter_rows(values_only=True)
    # the header row moved: the newer bill-tracker puts section bands on row 1
    # and the real headers on row 2 — detect it (the user 2026-07-24).
    idx: Dict[str, int] = {}
    for _ in range(6):
        try:
            row = next(it)
        except StopIteration:
            break
        names = [str(c).strip() if c is not None else "" for c in row]
        if "Vendor" in names and "Bill Open Bal" in names:
            idx = {n: i for i, n in enumerate(names) if n}
            break
    if not idx:
        wb.close()
        return [], synced

    # The Bill Tracker renames columns as it evolves ("Payment Date" → "GC Paid
    # Date", "Status" → "Pay Status" on 2026-07-28). Accept known aliases so a
    # rename degrades to nothing worse than a blank, never a silent $0 bucket.
    ALIASES = {
        "Payment Date": ("Payment Date", "GC Paid Date"),
        "Status": ("Status", "Pay Status", "Invoice Status"),
        "Matched Invoice": ("Matched Invoice", "Invoice #"),
    }

    def cell(row, name):
        for cand in ALIASES.get(name, (name,)):
            i = idx.get(cand)
            if i is not None and i < len(row) and row[i] not in (None, ""):
                return row[i]
        i = idx.get(name)
        return row[i] if i is not None and i < len(row) else None

    today = _today()
    bills: Dict[Any, Dict[str, Any]] = {}
    for row in it:
        vendor = cell(row, "Vendor")
        billno = cell(row, "Bill #")
        if not vendor:
            continue
        key = (vendor, billno)
        if key in bills:
            continue                        # bill-level fields repeat per line
        openbal = float(cell(row, "Bill Open Bal") or 0)
        if openbal <= 0:                    # already paid to the sub — skip
            continue
        division = cell(row, "Division")
        bdate = cell(row, "Bill Date")
        minv = cell(row, "Matched Invoice")
        pdate = cell(row, "Payment Date")
        deadline, days, lien_state = _bill_lien(division, bdate, today)
        note = str(cell(row, "Line Description") or "")
        bills[key] = {
            "vendor": str(vendor), "bill": str(billno or ""),
            "date": bdate.date() if isinstance(bdate, dt.datetime) else bdate,
            "division": division or "?", "project": str(cell(row, "Project #") or ""),
            "open": openbal,
            "invoice": str(minv or ""),
            "invoice_date": cell(row, "Invoice Date"),
            "paid_date": pdate.date() if isinstance(pdate, dt.datetime) else pdate,
            "status": str(cell(row, "Status") or ""),
            "ar": _ar_state(minv, pdate),
            "deadline": deadline, "days": days, "lien": lien_state,
            "note": note[:60],
        }
    wb.close()
    return list(bills.values()), synced


